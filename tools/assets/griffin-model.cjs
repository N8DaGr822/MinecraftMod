const parentById=new Map(), cubeParent=new Map();
function visit(node,parent) {
  if(typeof node==='string') {cubeParent.set(node,parent);return;}
  parentById.set(node.uuid,parent);
  node.children.forEach(child=>visit(child,node.uuid));
}
rig.model.outliner.forEach(node=>visit(node));
function groundPoint(point,id) {
  if(!id)return point;
  const g=rig.model.groups.find(g=>g.uuid===id);
  const frame=rig.model.animations[0].animators[id].keyframes.find(f=>f.channel==='rotation');
  const r=['x','y','z'].map(a=>Number(frame.data_points[0][a])/degrees);
  let [x,y,z]=point.map((v,i)=>v-g.origin[i]);
  [y,z]=[y*Math.cos(r[0])-z*Math.sin(r[0]),y*Math.sin(r[0])+z*Math.cos(r[0])];
  [x,z]=[x*Math.cos(r[1])+z*Math.sin(r[1]),-x*Math.sin(r[1])+z*Math.cos(r[1])];
  [x,y]=[x*Math.cos(r[2])-y*Math.sin(r[2]),x*Math.sin(r[2])+y*Math.cos(r[2])];
  return groundPoint([x,y,z].map((v,i)=>v+g.origin[i]),parentById.get(id));
}
