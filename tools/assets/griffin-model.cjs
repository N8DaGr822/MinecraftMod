const number = n => Number.isInteger(n) ? String(n) : `${n}F`;
function part(name, parent, pivot, cubes) {
  const absolute = pivot.map((v,i)=>v+(parts.get(parent)?.[i]||0));
  parts.set(name,absolute);
  rig.bone(name,[absolute[0]/16,(24-absolute[1])/16,absolute[2]/16],parent==='root'?undefined:parent);
  let builder='CubeListBuilder.create()';
  cubes.forEach(([label,u,v,x,y,z,w,h,d])=>{
    if(u+2*(w+d)>128 || v+d+h>128) throw Error('UV overflow: '+label);
    builder+=`\n\t\t\t.texOffs(${u}, ${v}).addBox(${[x,y,z,w,h,d].map(number).join(', ')})`;
    const c=rig.box(name+'_'+label,name,(absolute[0]+x+w/2)/16,(24-absolute[1]-y-h)/16,(absolute[2]+z+d/2)/16,w/16,h/16,d/16);
    c.uv_offset=[u,v];
  });
  lines.push(`\t\tvar ${name} = ${parent}.addOrReplaceChild("${name}", ${builder},\n\t\t\tPartPose.offset(${pivot.map(number).join(', ')}));`);
}
